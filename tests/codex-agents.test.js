const SCRIPT = path.join(SCRIPTS, 'codex-agents.js');
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'agent-team-cx-'));
const ROLES = ['architect', 'coach', 'implementer', 'reviewer', 'scout'];

function writeMap(map) {
  const f = path.join(tmp(), 'models.json');
  fs.writeFileSync(f, JSON.stringify(map));
  return f;
}
function gen(out, { map, args = [], agents } = {}) {
  const a = [SCRIPT, '--out', out, ...(agents ? ['--agents', agents] : []), ...args];
  const env = { ...process.env };
  if (map) env.AGENT_TEAM_MODELS = map; else delete env.AGENT_TEAM_MODELS;
  env.HOME = env.USERPROFILE = tmp(); // no real user override
  return spawnSync('node', a, { encoding: 'utf8', env });
}
const tomls = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.toml')).sort() : []);

// Minimal TOML reader for the subset we emit: header comment, `key = "basic"`,
// `key = '''literal'''` (multi-line).
function parseToml(text) {
  const lines = text.split('\n');
  const out = {};
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (!l || l.startsWith('#')) continue;
    const m = /^([a-z_]+) = (.*)$/.exec(l);
    assert(m, `bad line: ${l}`);
    const [, k, rest] = m;
    if (rest === "'''") {
      let j = i + 1;
      const buf = [];
      while (j < lines.length && !lines[j].startsWith("'''")) buf.push(lines[j++]);
      assert(j < lines.length, 'unterminated literal');
      const tail = lines[j].slice(3);
      out[k] = buf.join('\n') + (buf.length ? '\n' : '') + '';
      assert(tail === '', 'junk after closing quotes');
      i = j;
    } else {
      assert(rest.startsWith('"') && rest.endsWith('"'), `bad basic string: ${rest}`);
      let s = '';
      const body = rest.slice(1, -1);
      for (let p = 0; p < body.length; p++) {
        const c = body[p];
        if (c === '"') throw new Error('unescaped quote');
        if (c !== '\\') { s += c; continue; }
        const n = body[++p];
        if (n === 'n') s += '\n';
        else if (n === 't') s += '\t';
        else if (n === 'r') s += '\r';
        else if (n === '\\' || n === '"') s += n;
        else if (n === 'u') { s += String.fromCharCode(parseInt(body.slice(p + 1, p + 5), 16)); p += 4; }
        else throw new Error('bad escape');
      }
      out[k] = s;
    }
  }
  return out;
}

const DEF = path.join(ROOT, 'config', 'models.json');
const defMap = JSON.parse(fs.readFileSync(DEF, 'utf8'));

test('default map gives 15 files, no xlarge, with the required keys', () => {
  const out = path.join(tmp(), 'not', 'yet', 'there'); // out dir does not exist
  const r = gen(out);
  eq(r.status, 0, r.stderr);
  const files = tomls(out);
  eq(files.length, 15);
  assert(!files.some((f) => f.includes('xlarge')), 'xlarge present');
  for (const role of ROLES) for (const t of ['small', 'medium', 'large']) assert(files.includes(`${role}-${t}.toml`), `${role}-${t}`);
  const t = parseToml(fs.readFileSync(path.join(out, 'implementer-medium.toml'), 'utf8'));
  eq(t.name, 'implementer-medium');
  eq(t.model, defMap.medium.codex);
  assert(t.description.endsWith(' (tier medium)'), t.description);
  assert(!('model_reasoning_effort' in t));
  assert(t.developer_instructions.includes('You are the **implementer**'));
  const first = fs.readFileSync(path.join(out, 'implementer-medium.toml'), 'utf8').split('\n')[0];
  assert(/^# generated by agent-team \S+ \(role implementer, tier medium\); regenerate with scripts\/codex-agents\.js$/.test(first), first);
  assert(!/[A-Za-z]:\\|\/Users\/|\/home\//.test(fs.readFileSync(path.join(out, 'implementer-medium.toml'), 'utf8').split('\n').slice(0, 4).join('\n')), 'absolute path');
});

test('xlarge enabled on the tier gives 20 files', () => {
  const m = JSON.parse(JSON.stringify(defMap));
  m.xlarge.enabled = true;
  const out = tmp();
  eq(gen(out, { map: writeMap(m) }).status, 0);
  const files = tomls(out);
  eq(files.length, 20);
  assert(files.includes('scout-xlarge.toml'));
  eq(parseToml(fs.readFileSync(path.join(out, 'scout-xlarge.toml'), 'utf8')).model, 'gpt-6-astra');
});

test('credits entry without explicit enabled is skipped; with enabled: true it is written', () => {
  const m = { small: { codex: { model: 'm-small' } }, medium: { codex: { model: 'm-cred', billing: 'credits' } } };
  const out = tmp();
  eq(gen(out, { map: writeMap(m) }).status, 0);
  assert(tomls(out).every((f) => f.endsWith('-small.toml')), tomls(out).join());
  eq(tomls(out).length, 5);
  m.medium.codex.enabled = true;
  eq(gen(out, { map: writeMap(m) }).status, 0);
  eq(tomls(out).length, 10);
});

test('an override dropping medium writes no medium file and removes a stale one', () => {
  const out = tmp();
  eq(gen(out).status, 0);
  assert(fs.existsSync(path.join(out, 'scout-medium.toml')), 'precondition: medium generated');
  const m = JSON.parse(JSON.stringify(defMap));
  delete m.medium;
  const r = gen(out, { map: writeMap(m) });
  eq(r.status, 0);
  assert(!tomls(out).some((f) => f.includes('-medium')), 'medium remains');
  eq(tomls(out).length, 10);
  // one step past: a second run changes nothing
  assert(/0 written, 10 unchanged, 0 removed/.test(gen(out, { map: writeMap(m) }).stdout));
});

test('Codex-less map writes nothing, says so, exits 0 and removes generated files', () => {
  const out = tmp();
  gen(out);
  assert(tomls(out).length === 15, 'precondition');
  fs.writeFileSync(path.join(out, 'mine.toml'), 'name = "mine"\n');
  const r = gen(out, { map: writeMap({ small: { claude: 'haiku' } }) });
  eq(r.status, 0);
  assert(/No Codex entries/.test(r.stdout), r.stdout);
  eq(tomls(out).join(), 'mine.toml');
});

test('a user file without the header is kept and warned about', () => {
  const out = tmp();
  fs.mkdirSync(out, { recursive: true });
  const mine = path.join(out, 'scout-small.toml');
  fs.writeFileSync(mine, 'name = "mine"\n');
  const r = gen(out);
  eq(r.status, 0);
  eq(fs.readFileSync(mine, 'utf8'), 'name = "mine"\n');
  assert(/warning: scout-small\.toml/.test(r.stdout), r.stdout);
  eq(tomls(out).length, 15);
  // survives removal pass too
  gen(out, { map: writeMap({}) });
  assert(fs.existsSync(mine));
});

test('TOML round-trips a body with quotes, backticks, triple quotes, CRLF; no-frontmatter agent works; role with colon', () => {
  const agents = tmp();
  const nasty = 'Say "hi" and use `code`.\nBackslash \\ and \'single\' and \'\'\' triple.\nend';
  fs.writeFileSync(path.join(agents, 'weird.md'), `---\nname: team:weird\ndescription: Does "things": well\ntier: small\n---\n\n${nasty}\n`);
  fs.writeFileSync(path.join(agents, 'plain.md'), 'Just a body with `ticks` and "quotes".\n');
  fs.writeFileSync(path.join(agents, 'crlf.md'), '---\r\nname: crlf\r\ndescription: Win file\r\n---\r\nline one\r\nline two\r\n');
  fs.writeFileSync(path.join(agents, 'quote.md'), 'ends with a quote \'');
  const out = tmp();
  eq(gen(out, { agents }).status, 0);
  eq(tomls(out).length, 12);
  const files = tomls(out);
  assert(files.includes('team-weird-small.toml'), files.join()); // ':' made file-safe
  const w = parseToml(fs.readFileSync(path.join(out, 'team-weird-small.toml'), 'utf8'));
  eq(w.name, 'team:weird-small');
  eq(w.description, 'Does "things": well (tier small)');
  eq(w.developer_instructions, nasty + '\n');
  // literal string used when safe
  assert(fs.readFileSync(path.join(out, 'plain-small.toml'), 'utf8').includes("developer_instructions = '''\n"));
  eq(parseToml(fs.readFileSync(path.join(out, 'plain-medium.toml'), 'utf8')).developer_instructions, 'Just a body with `ticks` and "quotes".\n');
  const c = fs.readFileSync(path.join(out, 'crlf-large.toml'), 'utf8');
  assert(!c.includes('\r'), 'CR leaked');
  eq(parseToml(c).developer_instructions, 'line one\nline two\n');
  eq(parseToml(fs.readFileSync(path.join(out, 'quote-small.toml'), 'utf8')).developer_instructions, 'ends with a quote \'');
});

test('--check: exit 1 when missing, stale or edited; 0 when current; never writes', () => {
  const out = path.join(tmp(), 'o');
  eq(gen(out, { args: ['--check'] }).status, 1); // missing
  assert(!fs.existsSync(out), 'check created the dir');
  eq(gen(out).status, 0);
  eq(gen(out, { args: ['--check'] }).status, 0);
  const f = path.join(out, 'coach-large.toml');
  const orig = fs.readFileSync(f, 'utf8');
  fs.writeFileSync(f, orig + '# edit\n');
  eq(gen(out, { args: ['--check'] }).status, 1); // out of date
  eq(fs.readFileSync(f, 'utf8'), orig + '# edit\n');
  fs.writeFileSync(f, orig);
  fs.writeFileSync(path.join(out, 'gone-small.toml'), orig);
  eq(gen(out, { args: ['--check'] }).status, 1); // stale
  assert(fs.existsSync(path.join(out, 'gone-small.toml')), 'check deleted');
  eq(gen(out).status, 0);
  eq(gen(out, { args: ['--check'] }).status, 0);
});

test('--dry-run changes nothing', () => {
  const out = path.join(tmp(), 'o');
  const r = gen(out, { args: ['--dry-run'] });
  eq(r.status, 0);
  assert(!fs.existsSync(out));
  assert(/15 to write/.test(r.stdout), r.stdout);
});

test('re-run is idempotent: files byte-identical, nothing rewritten', () => {
  const out = tmp();
  gen(out);
  const snap = (d) => tomls(d).map((f) => fs.readFileSync(path.join(d, f), 'utf8'));
  const before = snap(out);
  const r = gen(out);
  eq(r.status, 0);
  assert(/0 written, 15 unchanged/.test(r.stdout), r.stdout);
  eq(JSON.stringify(snap(out)), JSON.stringify(before));
});
