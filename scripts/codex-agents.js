#!/usr/bin/env node
// Generate one Codex agent TOML per role x enabled Codex tier from agents/*.md
// and the effective model map. Node built-ins only.
//   node scripts/codex-agents.js [--out <dir>] [--agents <dir>] [--dry-run] [--check]
// Default out dir: <git root>/.codex/agents. Exit 1 on --check drift or bad usage.
'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const models = require('./models.js');
const lib = require('./lib.js');

const HEADER_PREFIX = '# generated by agent-team ';
const DEFAULT_AGENTS = path.join(__dirname, '..', 'agents');

const isMap = (m) => m && typeof m === 'object' && !Array.isArray(m);

// Split an agent file into {fm, body}. Tolerates CRLF and a missing frontmatter.
function parseAgent(text) {
  const t = text.replace(/\r\n?/g, '\n').replace(/^﻿/, '');
  const m = /^---\n([\s\S]*?)\n---[ \t]*(?:\n|$)([\s\S]*)$/.exec(t);
  if (!m) return { fm: {}, body: t };
  const fm = {};
  for (const line of m[1].split('\n')) {
    const k = /^([A-Za-z_][\w-]*):[ \t]*(.*)$/.exec(line);
    if (k) fm[k[1]] = k[2].trim().replace(/^(["'])(.*)\1$/, '$2');
  }
  return { fm, body: m[2] };
}

// A tier qualifies when auto-eligible, or explicitly enabled: true (and not disabled).
function codexTiers(map) {
  const out = [];
  for (const tier of models.TIERS) {
    const e = models.entry(map, 'codex', tier);
    if (!e || !e.enabled) continue;
    const tierObj = map[tier];
    const raw = tierObj.codex;
    const explicit = tierObj.enabled === true || (isMap(raw) && raw.enabled === true);
    if (e.auto || explicit) out.push(e);
  }
  return out;
}

function basicString(s) {
  let o = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '\\') o += '\\\\';
    else if (ch === '"') o += '\\"';
    else if (ch === '\n') o += '\\n';
    else if (ch === '\t') o += '\\t';
    else if (ch === '\r') o += '\\r';
    else if (c < 0x20 || c === 0x7f) o += '\\u' + c.toString(16).padStart(4, '0');
    else o += ch;
  }
  return o + '"';
}

function multilineString(s) {
  // eslint-disable-next-line no-control-regex
  const unsafe = s.includes("'''") || s.endsWith("'") || /[\u0000-\u0008\u000b-\u001f\u007f]/.test(s);
  if (unsafe) return basicString(s);
  return "'''\n" + s + "'''";
}

const oneLine = (s) => String(s).replace(/[\r\n]+/g, ' ');

function render({ role, tier, model, description, body, version }) {
  return [
    `${HEADER_PREFIX}${oneLine(version)} (role ${oneLine(role)}, tier ${tier}); regenerate with scripts/codex-agents.js`,
    `name = ${basicString(`${role}-${tier}`)}`,
    `description = ${basicString(`${oneLine(description)} (tier ${tier})`)}`,
    `model = ${basicString(model)}`,
    `developer_instructions = ${multilineString(body)}`,
    '',
  ].join('\n');
}

const fileSafe = (s) => s.replace(/[^A-Za-z0-9._-]+/g, '-');

function gitRoot() {
  try {
    return execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return process.cwd();
  }
}

function desired({ agentsDir, map, version }) {
  const tiers = codexTiers(map);
  const files = new Map();
  let names = [];
  try { names = fs.readdirSync(agentsDir).filter((f) => f.endsWith('.md')).sort(); } catch { /* none */ }
  for (const f of names) {
    const { fm, body } = parseAgent(fs.readFileSync(path.join(agentsDir, f), 'utf8'));
    const role = fm.name || path.basename(f, '.md');
    const description = fm.description || `${role} agent`;
    const instructions = body.replace(/^\n+/, '');
    for (const e of tiers) {
      files.set(`${fileSafe(role)}-${e.tier}.toml`, render({ role, tier: e.tier, model: e.model, description, body: instructions, version }));
    }
  }
  return files;
}

function isGenerated(file) {
  try {
    return fs.readFileSync(file, 'utf8').startsWith(HEADER_PREFIX);
  } catch {
    return false;
  }
}

function sync({ out, agentsDir = DEFAULT_AGENTS, map, version = lib.guidanceVersion(), dryRun = false, check = false, log = console.log }) {
  const want = desired({ agentsDir, map, version });
  const r = { written: [], unchanged: [], removed: [], skipped: [], drift: false, count: want.size };
  const readonly = dryRun || check;
  if (!readonly && want.size) fs.mkdirSync(out, { recursive: true });
  for (const [file, content] of want) {
    const p = path.join(out, file);
    if (fs.existsSync(p)) {
      if (!isGenerated(p)) {
        log(`warning: ${file} exists and was not generated by agent-team; skipping`);
        r.skipped.push(file);
        continue;
      }
      if (fs.readFileSync(p, 'utf8') === content) { r.unchanged.push(file); continue; }
    }
    r.drift = true;
    r.written.push(file);
    if (!readonly) fs.writeFileSync(p, content, 'utf8');
  }
  let existing = [];
  try { existing = fs.readdirSync(out).filter((f) => f.endsWith('.toml')); } catch { /* no dir */ }
  for (const file of existing) {
    if (want.has(file) || !isGenerated(path.join(out, file))) continue;
    r.drift = true;
    r.removed.push(file);
    if (!readonly) fs.unlinkSync(path.join(out, file));
  }
  if (!want.size) log('No Codex entries enabled in the model map; no agent files generated.');
  const pending = check || dryRun;
  log(`codex agents: ${r.written.length} ${pending ? (check ? 'missing or out of date' : 'to write') : 'written'}, ` +
    `${r.unchanged.length} unchanged, ${r.removed.length} ${pending ? 'stale' : 'removed'}, ${r.skipped.length} skipped (${out})`);
  for (const f of r.written) log(`  ${pending ? 'would write' : 'wrote'}: ${f}`);
  for (const f of r.removed) log(`  ${pending ? 'stale' : 'removed'}: ${f}`);
  return r;
}

function main(argv) {
  let out = null;
  let agentsDir = DEFAULT_AGENTS;
  let dryRun = false;
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--out' || a === '--agents') {
      const v = argv[++i];
      if (!v || v.startsWith('--')) { console.error(`${a} requires a value`); return 1; }
      if (a === '--out') out = path.resolve(v); else agentsDir = path.resolve(v);
    } else if (a === '--dry-run') dryRun = true;
    else if (a === '--check') check = true;
    else { console.error('usage: codex-agents.js [--out <dir>] [--agents <dir>] [--dry-run] [--check]'); return 1; }
  }
  const loaded = models.loadMap();
  if (loaded.error) console.error(`warning: model map: ${loaded.error}`);
  const r = sync({ out: out || path.join(gitRoot(), '.codex', 'agents'), agentsDir, map: loaded.map, dryRun, check });
  return check && r.drift ? 1 : 0;
}

module.exports = { parseAgent, codexTiers, render, desired, sync, multilineString, basicString };

if (require.main === module) process.exitCode = main(process.argv.slice(2));
